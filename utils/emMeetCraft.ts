/**
 * 见面两种模式（长文 / 立绘）共用的几条写法（2026-11-17 阿萌从酒馆预设里挑的思路，措辞是自己写的）：
 * - 拆开她写的话：说出口的听得见、做出来的看得见，括号和星号里的心里话、旁白看不见（Ariadne「处理输入」的意思）
 * - 按字面接她的话（跟聊天 2.9 同一句，emFaceValueLine）
 * - 默认简笔，只在一处写细；同一件小东西不连着两轮当主角
 * 禁八股那一类不在这里：阿萌自己用世界书加。
 */
import { emFaceValueLine } from './emPromptAddons';

export const composeMeetCraftBlock = (userName: string): string => {
    const you = userName.trim() || '对方';
    return `### ${you}写的话，你接得住哪些
${you}一轮里常常混着好几种东西，先分开再接：
- 引号里，或者「：」后面说出口的话：你听得见。
- ${you}做的动作、脸上的表情：你们在同一个地方时，你看得见。
- 括号里、星号里的心里话和旁白：你看不见也听不见。不回应它，不让它悄悄影响你的话和动作，也不碰巧说中它。
你只能从听到的、看到的和你本来就知道的事里反应；猜错了就是猜错了，这很正常。
- ${emFaceValueLine(you)}

### 写细一处就够
- 平时直接写，一句交代清楚就往下走。只有你心里的变化大到改了你接下来做什么、说什么，才停下来写细；只挑一处，写完马上回到平常的写法。
- 同一件小东西（一杯茶、一张纸、一件外套）不连着两轮当主角，它的事做完了就放下。

`;
};
